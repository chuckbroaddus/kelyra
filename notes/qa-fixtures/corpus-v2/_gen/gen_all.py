def main():
    print("Building corpus-v2 …")
    for subj in ("math", "science", "history", "english"):
        generate_pack(subj)
    generate_homework()
    generate_worksheets()
    generate_papers()
    generate_admin()
    write_readme()
    write_manifest()
    print(f"DONE · total ≈ {du_mb(ROOT):.1f} MB")


if __name__ == "__main__":
    main()
