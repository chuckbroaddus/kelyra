#!/usr/bin/env python3
"""Build full corpus-v2 and write MANIFEST.md + size report."""
from __future__ import annotations

import sys
from pathlib import Path

# allow running from _gen/
sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import ROOT, page_count_pdf
from gen_admin import generate_admin
from gen_homework import generate_homework
from gen_papers import generate_papers
from gen_quizzes import generate_pack
from gen_worksheets import generate_worksheets


def du_mb(path: Path) -> float:
    total = 0
    if path.is_file():
        return path.stat().st_size / (1024 * 1024)
    for p in path.rglob("*"):
        if p.is_file() and ".venv" not in p.parts and p.suffix != ".pyc":
            total += p.stat().st_size
    return total / (1024 * 1024)


def write_manifest():
    lines = [
        "# corpus-v2 MANIFEST",
        "",
        "Generated by `notes/qa-fixtures/corpus-v2/_gen/gen_all.py`.",
        "License: **CC0 1.0** synthetic originals for Kelyra QA.",
        "Handwriting on student pages is **simulated** (fonts/jitter/scratch-outs).",
        "",
        "## Grading packs (32 students each)",
        "",
        "| Pack | Flatbed pages | Key | Phone JPGs |",
        "|------|---------------|-----|------------|",
    ]
    for subj in ("math", "science", "history", "english"):
        d = ROOT / "grading" / f"{subj}-quiz-32"
        stack = d / "stack-flatbed.pdf"
        pages = page_count_pdf(stack) if stack.exists() else "?"
        phones = sorted((d / "stack-phone").glob("*.jpg")) if (d / "stack-phone").exists() else []
        lines.append(f"| `{subj}-quiz-32` | {pages} | answer-key.pdf | {len(phones)} |")
    lines += [
        "",
        "## Homework",
        "",
    ]
    for folder in ("math-hw-12", "english-hw-10"):
        d = ROOT / "homework" / folder
        pages = page_count_pdf(d / "stack-flatbed.pdf") if (d / "stack-flatbed.pdf").exists() else "?"
        lines.append(f"- `{folder}/` — stack pages: **{pages}** + answer-key.pdf")
    lines += [
        "",
        "## Worksheets",
        "- `worksheets/math-graph-assessment/` — graph interpretation + key",
        "- `worksheets/science-diagram-assessment/` — plant-cell labels + key",
        "",
        "## Papers",
        "- `papers/typed-research-sample.pdf`",
        "- `papers/handwritten-draft.pdf` + `handwritten-draft-phone.jpg`",
        "",
        "## Admin",
        "",
    ]
    admin = ROOT / "admin"
    for p in sorted(admin.glob("*.pdf")):
        lines.append(f"- `admin/{p.name}`")
    lines += [
        "",
        f"## Size",
        f"",
        f"- corpus-v2 total (excluding `_gen/.venv`): **{du_mb(ROOT):.1f} MB**",
        "",
        "## Regenerate",
        "",
        "```bash",
        "cd notes/qa-fixtures/corpus-v2/_gen",
        "python3 -m venv .venv && .venv/bin/pip install -r requirements.txt",
        ".venv/bin/python gen_all.py",
        "```",
        "",
    ]
    (ROOT / "MANIFEST.md").write_text("\n".join(lines) + "\n")
    print("wrote MANIFEST.md")


