import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontsDir = join(root, 'node_modules/katex/dist/fonts');
const katexCssPath = join(root, 'node_modules/katex/dist/katex.min.css');
const outPath = join(root, 'src/components/ui/katexMinCssNative.generated.ts');

function katexCssWithDataWoff2(css, fontsByFile) {
  let out = css;
  for (const [file, b64] of Object.entries(fontsByFile)) {
    const from = `url(fonts/${file}) format("woff2")`;
    const to = `url(data:font/woff2;base64,${b64}) format("woff2")`;
    if (!out.includes(from)) {
      throw new Error(`Missing woff2 url for ${file} in katex.min.css`);
    }
    out = out.split(from).join(to);
  }
  out = out.replace(/,url\(fonts\/[^)]+\.woff\) format\("woff"\)/g, '');
  out = out.replace(/,url\(fonts\/[^)]+\.ttf\) format\("truetype"\)/g, '');
  if (/url\(fonts\//.test(out)) {
    throw new Error('Residual relative fonts/ URLs after embed');
  }
  if (!/data:font\/woff2;base64,/.test(out)) {
    throw new Error('No data:font/woff2 URLs produced');
  }
  return out;
}

const woff2Files = readdirSync(fontsDir).filter((f) => f.endsWith('.woff2')).sort();
if (woff2Files.length === 0) {
  throw new Error(`No woff2 fonts in ${fontsDir}`);
}

const fontsByFile = Object.fromEntries(
  woff2Files.map((file) => [file, readFileSync(join(fontsDir, file)).toString('base64')]),
);

const css = readFileSync(katexCssPath, 'utf8').trimEnd();
const nativeCss = katexCssWithDataWoff2(css, fontsByFile);

const body = `/** AUTO-GENERATED by scripts/build-katex-native-css.mjs — do not edit. */
/** KaTeX min CSS with woff2 fonts inlined as data: URLs (about:blank-safe). */
export const KATEX_MIN_CSS_NATIVE = ${JSON.stringify(nativeCss)};
`;

writeFileSync(outPath, body);
const bytes = Buffer.byteLength(nativeCss, 'utf8');
console.log(
  `Wrote ${outPath} (${woff2Files.length} fonts, ${bytes} css chars)`,
);
